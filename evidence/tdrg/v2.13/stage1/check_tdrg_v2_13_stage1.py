def live(t):
    return t[:t.index("\n## Appendix A")]


def section(t, head, nxt="\n## "):
    a = t.index(head); z = t.index(nxt, a + 1)
    return t[a:z]


def outside1(t):
    s1 = section(t, "## §1.")
    return live(t).replace(s1, "")


# ------------------------------------------------------------------ gates
def gates(base, cand, log):
    R = []
    def g(name, ok, info=""):
        R.append((name, bool(ok), info))

    g("C0 base", sha(base) == B.BASE_SHA, sha(base)[:16])

    try:
        B.LOG.clear(); rebuilt = B.build(base)
        g("C1 build", rebuilt == cand and json.loads(json.dumps({"edits": B.LOG}, ensure_ascii=False))["edits"] == log["edits"]
          and log["intermediate_sha256"] == sha(cand), "%d edits; intermediate %s" % (len(B.LOG), sha(cand)[:16]))
    except SystemExit:
        g("C1 build", False, "builder stopped")

    anchors = [e.get("line_anchor") or e.get("after") for e in log["edits"] if e["mode"] != "range"]
    spans = []
    for e in log["edits"]:
        if e["mode"] == "range":
            bl = base.split("\n")
            a = [i for i, l in enumerate(bl) if l.startswith(e["start"])]
            z = [i for i, l in enumerate(bl) if l.startswith(e["end"])]
            if len(a) == 1 and len(z) == 1:
                spans.append("\n".join(bl[a[0]:z[0]]))
    pb, pc = live(base).split("\n\n"), live(cand).split("\n\n")
    bad = []
    for op, i1, i2, j1, j2 in difflib.SequenceMatcher(None, pb, pc, autojunk=False).get_opcodes():
        if op == "equal":
            continue
        for p in pb[i1:i2]:
            if not any(a and a in p for a in anchors) and not any(p.strip("\n") in sp for sp in spans):
                bad.append(p[:80])
    g("C2 confined", not bad, "undeclared changes: %s" % bad[:3] if bad else "every changed base paragraph carries a logged anchor")

    db, dc = collections.Counter(RID_DECL.findall(live(base))), collections.Counter(RID_DECL.findall(live(cand)))
    lost = sorted(r for r in db if dc[r] != db[r])
    ids_b, ids_c = set(RID_ANY.findall(live(base))), set(RID_ANY.findall(live(cand)))
    newid = ids_c - ids_b
    g("C3 RIDs", not lost and newid == NEW_IDS, "lost/changed declarations %s; new identifiers %s" % (lost, sorted(newid)))

    def tags(t):
        return collections.Counter(TAG.findall(t[t.index("\n## §2."):t.index("\n## Appendix A")]))
    tb, tc = tags(base), tags(cand)
    g("C4 tags", dict(tb - tc) == TAG_OUT and dict(tc - tb) == TAG_IN, "out %s, in %s" % (dict(tb - tc), dict(tc - tb)))

    def opens(t):
        out = {}
        for m in re.finditer(r"^\*\*(OPEN[^*]*|TDR-24F[^*]*)\*\* \[RID: (TDRG-OPEN-[A-Z0-9-]+)\]\n\nStatus: ([^\n]*)", t, re.M):
            out[m.group(2)] = (m.group(1), m.group(3))
        return out
    ob, oc = opens(live(base)), opens(live(cand))
    g("C5 OPEN", ob == oc and len(ob) >= 20, "%d OPEN records, headings and Status lines identical" % len(oc) if ob == oc else
      "changed: %s" % sorted(k for k in ob if ob.get(k) != oc.get(k)))

    az = {t: [l for l in git("%s:dsn/RTG_ARITHMETIC_RESONANCE_AND_ZETA_DSN.md" % t).split("\n")
              if "There is no closed non-backtracking walk of length 2 or 3" in l] for t in ("az-v0.6", "az-v0.7", "az-v0.8")}
    ofn = git("ofn-v0.12:dsn/RTG_ONTOLOGICAL_FOUNDATIONS.md")
    az8 = git("az-v0.8:dsn/RTG_ARITHMETIC_RESONANCE_AND_ZETA_DSN.md")
    prog = git("programme-v1.4:dsn/RTG_PROGRAMME_OVERVIEW.md")
    L = live(cand)
    stale = [s for s in ("az-v0.7", "az-v0.6", "FOUNDATIONS_v0.6", "`RTG_ONTOLOGICAL_FOUNDATIONS` v0.7", "DSN_METHODOLOGY_v1.2",
                         "deferred to v2.13", "deferred** to v2.13", "v2.13 layout work", "AZ v0.7", "declared v1.2") if s in L]
    ok6 = (all(len(v) == 1 for v in az.values()) and az["az-v0.6"] == az["az-v0.7"] == az["az-v0.8"]
           and "**OPEN-OFN-2 — Discrete interaction and policy selection** [RID: RTG-OFN-OPEN-DISC-INTERACTION]" in ofn
           and re.search(r"IMP-O08-06\*\* \[RID: TDRG-ALG-LEM-NOANNIHIL\]", ofn) and re.search(r"IMP-O08-14\*\* \[RID: TDRG-DEF-CONV-TICK\]", ofn)
           and "### Branch-local context from `RTG_DISCRETE_GENESIS_DSN` v2.12.14 (`tdrg-v2.12.14`) — clauses IMP-B" in az8
           and "counting observables" not in prog.lower() and "(`az-v0.8`)" in L and not stale)
    g("C6 pins", ok6, "AZ entry sha %s at v0.6/v0.7/v0.8; stale strings %s" % (sha(az["az-v0.8"][0])[:12] if az["az-v0.8"] else "-", stale))

    s1 = section(cand, "## §1.")
    words = len(s1.split()) - 4
    rids = set(re.findall(r"\b(TDRG-[A-Z0-9-]+[A-Z0-9])\b", s1))
    undeclared = sorted(r for r in rids if "[RID: %s]" % r not in L)
    rest = outside1(cand)
    nohome = [n for n, s, _ in HOMES if s not in rest]
    g("C7 §1", words <= 420 and not undeclared and not nohome,
      "%d words; %d RIDs named, undeclared %s; %d homes checked, missing %s" % (words, len(rids), undeclared, len(HOMES), nohome))

    a = cand.index("### §A.sim — Simulation Artifact Evolution `[ENG]`")
    blk = cand[a:cand.index("\n---", a)].split("\n", 2)[2].strip("\n")
    res = "`[RESULT]` Policy and bookkeeping bugs can invert the cosmological interpretation."
    appx = blk.split("\n\n")[0]
    sec8 = section(cand, "## §8.")
    g("C8 §A.sim", appx.startswith("| Version |") and blk.endswith(res) and sec8.count(appx) == 1 and res not in L,
      "table %d bytes, verbatim in §8; closing [RESULT] not in the live text" % len(appx.encode()))

    hyp = [l for l in base.split("\n") if l.startswith("**`[REVISED]` v2.8 failed-relock hypothesis")][0].split(":** ", 1)[1]
    appb = section(cand, "## Appendix B", "\n---")
    g("C9 App. B", ('Original: "%s"' % hyp) in appb and hyp not in L, "original statement quoted; removed from §2")

    h = cand[:cand.index("## Local Tag Aliases")]
    summ = re.search(r"^\*\*Status summary:\*\* (.*)$", h, re.M).group(1)
    sents = [x for x in re.split(r"(?<=[.)])\s+(?=[A-Z])", summ) if x.strip()]
    nums = set(re.findall(r"\d+\.\d+|\d{3,}", summ))
    g("C10 header", "**DSN Methodology:** DSN_METHODOLOGY_v1.4 (`methodology-v1.4`)" in h and 2 <= len(sents) <= 4
      and all(n in L.replace(h, "") for n in nums), "%d summary sentences; numbers %s found in the live text" % (len(sents), sorted(nums)))
    return R


def report(R):
    for n, ok, info in R:
        print("[%s] %s — %s" % ("PASS" if ok else "FAIL", n, info))
    print("RESULT: %d/%d gates pass" % (sum(ok for _, ok, _ in R), len(R)))


def controls(base, cand, log):
    M = [
        ("K1 AZ pin back to az-v0.7", "C6", lambda t: t.replace("(`az-v0.8`)", "(`az-v0.7`)", 1)),
        ("K2 tag changed in an untouched paragraph", "C4",
         lambda t: t.replace("`[NUM strong]` **Tail suppression with rare locking failure.**", "`[ALG]` **Tail suppression with rare locking failure.**", 1)),
        ("K3 RID declaration dropped", "C3", lambda t: t.replace("[RID: TDRG-THM-RECURRENCE] ", "", 1)),
        ("K4 OPEN Status line changed", "C5", lambda t: t.replace("Status: ACTIVE — PARTIAL", "Status: CLOSED", 1)),
        ("K5 §1 home lost", "C7", lambda t: t.replace("Verified to $< 10^{-18}$", "Verified", 1)),
        ("K6 §A.sim copy altered", "C8", lambda t: t.replace("| v3 | Star string fixed; births occur | `[ENG]` |\n| v4",
                                                               "| v3 | Star string fixed | `[ENG]` |\n| v4", 1)),
        ("K7 Appendix B paraphrased", "C9", lambda t: t.replace('Original: "the runaway is *not*', 'Original: "the runaway is not', 1)),
        ("K8 fifth summary sentence", "C10", lambda t: t.replace("relabelling-covariant on the canonical branch (SG-14).",
            "relabelling-covariant on the canonical branch (SG-14). It is complete. It is closed.", 1)),
        ("K9 stale v2.13 promise reintroduced", "C6", lambda t: t.replace("**open**, a separate decision of both owners", "**deferred** to v2.13", 1)),
        ("K10 unpaired [RESULT] promoted to §8 (review R1)", "C8", lambda t: t.replace(
            "| v13 | CLI support + corrected `orientation_ties` counter | `[ENG]` |\n\n---",
            "| v13 | CLI support + corrected `orientation_ties` counter | `[ENG]` |\n\n"
            "`[RESULT]` Policy and bookkeeping bugs can invert the cosmological interpretation.\n\n---", 1)),
    ]
    caught = 0
    for name, target, f in M:
        mut = f(cand)
        assert mut != cand, name
        R = dict((n.split()[0], ok) for n, ok, _ in gates(base, mut, log))
        hit = (not R[target]) and (not R["C1"])
        caught += hit
        print("%s: %s (target %s %s; C1 %s)" % (name, "CAUGHT" if hit else "MISSED", target,
                                                  "FAIL" if not R[target] else "pass", "FAIL" if not R["C1"] else "pass"))
    print("CONTROLS: %d/%d caught" % (caught, len(M)))
    return caught == len(M)


def main():
    base = git("%s:%s" % (B.BASE_TAG, DSN))
    ipath = sys.argv[sys.argv.index("--intermediate") + 1] if "--intermediate" in sys.argv else os.path.join(ROOT, DSN)
    cand = open(ipath, encoding="utf-8").read()
    log = json.load(open(os.path.join(HERE, "edit_log.json"), encoding="utf-8"))
    if "--controls" in sys.argv:
        sys.exit(0 if controls(base, cand, log) else 1)
    R = gates(base, cand, log)
    report(R)
    sys.exit(0 if all(ok for _, ok, _ in R) else 1)


if __name__ == "__main__":
    main()
