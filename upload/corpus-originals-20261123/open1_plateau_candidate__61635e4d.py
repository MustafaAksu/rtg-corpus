"""
OPEN 1, candidate #1: plateau-attractor phase moments.
Test against the leading-order cascade criterion (from open1_moment_reduction.py):
    L := <cos phi_ds> + (sqrt3/2) <sin phi_ds> < 0   [cascade-necessary, leading]

The plateau-attractor distribution of phi_ds is generated by the certified
phase-drift law along the birth-race trajectory:
    dphi_ds = -(sqrt3/18144) Qs (1264 Qs^2 - 459)   per step,
starting from the certified birth phase phi_ds^(1) = pi + arctan(sqrt3/2).
We compute the race-averaged first moments and the lever L, and check how it
compares to the deterministic pinned-birth value.
"""
import math
SQRT3 = math.sqrt(3)
phi_birth = math.pi + math.atan(SQRT3/2)

def dphi_ds(Qs):
    return -(SQRT3/18144)*Qs*(1264*Qs**2 - 459)

def lever(c, s):  # L = <cos> + (sqrt3/2)<sin>
    return c + (SQRT3/2)*s

# (a) pinned-birth reference (deterministic, no drift)
cb, sb = math.cos(phi_birth), math.sin(phi_birth)
print(f"birth phase phi_ds^(1) = {phi_birth:.4f} rad ({math.degrees(phi_birth):.1f} deg)")
print(f"pinned-birth: <cos>={cb:.4f}, <sin>={sb:.4f}, lever L={lever(cb,sb):.4f}")
print(f"  (L<0 => leading-favorable)\n")

# (b) plateau-attractor: race-averaged moments under phase drift
def race_phase_moments(Qs0, kappa, Qs_ctrl=0.1, max_n=500000, weight='uniform'):
    Qs=Qs0; Qc=kappa**2*Qs**3; Qd=(7/1024)*Qs**3
    phi=phi_birth
    sumc=sums=w_tot=0.0
    for n in range(1,max_n+1):
        # weight choices: 'uniform' (per step), 'Qd' (by apex amplitude = contribution)
        w = 1.0 if weight=='uniform' else max(Qd,0)
        sumc += w*math.cos(phi); sums += w*math.sin(phi); w_tot += w
        phi += dphi_ds(Qs)
        Qs += 0.25*Qs**2 + (5/9)*Qs*Qc
        Qc += (5/12)*Qs*Qc + (1/3)*Qc**2
        Qd += 0.0  # phase-moment pass only
        if Qs>=Qs_ctrl: break
    return sumc/w_tot, sums/w_tot, n

kappa = -2*SQRT3/3
print("plateau-attractor race-averaged moments (uniform per-step weight):")
for Qs0 in [1e-3, 5e-3, 1e-2, 2e-2]:
    c,s,n = race_phase_moments(Qs0, kappa, weight='uniform')
    print(f"  Qs0={Qs0:.0e}: <cos>={c:.4f}, <sin>={s:.4f}, L={lever(c,s):+.4f}, steps={n}")

print("\nplateau-attractor (amplitude-weighted, weight=Qd):")
for Qs0 in [1e-3, 5e-3, 1e-2, 2e-2]:
    c,s,n = race_phase_moments(Qs0, kappa, weight='Qd')
    print(f"  Qs0={Qs0:.0e}: <cos>={c:.4f}, <sin>={s:.4f}, L={lever(c,s):+.4f}, steps={n}")

# (c) how far does phi drift over the race? (is 'plateau' ~ pinned?)
def phi_range(Qs0, kappa, Qs_ctrl=0.1, max_n=500000):
    Qs=Qs0; Qc=kappa**2*Qs**3; phi=phi_birth; phimin=phimax=phi
    for n in range(1,max_n+1):
        phi += dphi_ds(Qs); phimin=min(phimin,phi); phimax=max(phimax,phi)
        Qs+=0.25*Qs**2+(5/9)*Qs*Qc; Qc+=(5/12)*Qs*Qc+(1/3)*Qc**2
        if Qs>=Qs_ctrl: break
    return phimin, phimax, phi
print("\nphase drift range over race (Qs0=1e-3):")
pmin,pmax,pend = phi_range(1e-3,kappa)
print(f"  phi in [{pmin:.4f}, {pmax:.4f}], end={pend:.4f}; total drift={pend-phi_birth:+.2e} rad")
print(f"  drift is moderate (~0.81 rad) but remains entirely inside the favorable")
print(f"  (L<0) half-plane (130.9-310.9 deg), so the lever stays robustly negative.")
